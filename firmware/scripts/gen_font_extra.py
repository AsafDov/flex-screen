"""Generates src/fonts/font_extra.c: the characters LVGL's built-in Montserrat lacks.

LVGL ships Montserrat with ASCII and its symbols only, so "·", "…", dashes, curly quotes and
accented or Cyrillic letters in song titles, window titles and commit messages drew as boxes.
This renders them from the same Montserrat-Medium.ttf at the deck's three sizes into LVGL's
plain 4 bpp font format. Each font falls back to DejaVu (Hebrew, Arabic), and the shell makes
Montserrat fall back to these.

Run from firmware/ with any Python that has Pillow:
    python scripts/gen_font_extra.py
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

TTF = Path(".pio/libdeps/deck/lvgl/scripts/generators/built_in_font/Montserrat-Medium.ttf")
OUT = Path("src/fonts/font_extra.c")
SIZES = {14: (16, 3), 16: (18, 3), 20: (22, 4)}  # size: (line_height, base_line) of lv_font_montserrat_<size>
FALLBACK = "lv_font_dejavu_16_persian_hebrew"

BUILT_IN = {0xB0, 0x2022}  # degree and bullet are already in LVGL's Montserrat
CODEPOINTS = sorted(
    (set(range(0xA0, 0x100)) | set(range(0x100, 0x180)) | set(range(0x400, 0x460)) |
     {0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212}) - BUILT_IN)


def render(font: ImageFont.FreeTypeFont, size: int, cp: int):
    """Returns (adv_w in 1/16 px, box_w, box_h, ofs_x, ofs_y, 4-bit pixels row by row)."""
    ch = chr(cp)
    adv = round(font.getlength(ch) * 16)
    canvas = Image.new("L", (size * 4, size * 4), 0)
    ox, oy = size, size * 3  # pen position: left edge, baseline
    ImageDraw.Draw(canvas).text((ox, oy), ch, font=font, fill=255, anchor="ls")
    box = canvas.getbbox()
    if box is None:
        return adv, 0, 0, 0, 0, []
    left, top, right, bottom = box
    pixels = [(canvas.getpixel((x, y)) + 8) // 17 for y in range(top, bottom) for x in range(left, right)]
    return adv, right - left, bottom - top, left - ox, oy - bottom, pixels


def pack(pixels: list[int]) -> list[int]:
    """LVGL's plain format: one continuous stream of nibbles, high nibble first, no row padding."""
    if len(pixels) % 2:
        pixels = pixels + [0]
    return [(pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2)]


def font_source(size: int) -> str:
    line_height, base_line = SIZES[size]
    font = ImageFont.truetype(str(TTF), size)
    bitmap: list[int] = []
    glyphs = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,"]
    for cp in CODEPOINTS:
        adv, w, h, ox, oy, pixels = render(font, size, cp)
        glyphs.append(f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, "
                      f".ofs_x = {ox}, .ofs_y = {oy}}}, /* U+{cp:04X} */")
        bitmap += pack(pixels)
    start = CODEPOINTS[0]
    offsets = [cp - start for cp in CODEPOINTS]
    rows = lambda values: "\n".join("    " + ", ".join(f"0x{v:02x}" for v in values[i:i + 16]) + ","
                                    for i in range(0, len(values), 16))
    return f"""
/* {size} px */
static const uint8_t bitmap_{size}[] = {{
{rows(bitmap)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyphs_{size}[] = {{
{chr(10).join(glyphs)}
}};

static const lv_font_fmt_txt_cmap_t cmaps_{size}[] = {{
    {{.range_start = {start}, .range_length = {CODEPOINTS[-1] - start + 1}, .glyph_id_start = 1,
     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(offsets)},
     .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},
}};

static const lv_font_fmt_txt_dsc_t dsc_{size} = {{
    .glyph_bitmap = bitmap_{size},
    .glyph_dsc = glyphs_{size},
    .cmaps = cmaps_{size},
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t font_extra_{size} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {line_height},
    .base_line = {base_line},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
    .static_bitmap = 1,
    .dsc = &dsc_{size},
    .fallback = &{FALLBACK},
    .user_data = NULL,
}};
"""


def main() -> None:
    start = CODEPOINTS[0]
    offsets = [cp - start for cp in CODEPOINTS]
    unicode_list = "\n".join("    " + ", ".join(f"0x{v:04x}" for v in offsets[i:i + 12]) + ","
                             for i in range(0, len(offsets), 12))
    text = f"""/* Generated by scripts/gen_font_extra.py from Montserrat-Medium.ttf; don't edit by hand.
 * Latin-1, Latin Extended-A, basic Cyrillic and punctuation that LVGL's Montserrat lacks. */
#include "lvgl.h"

static const uint16_t unicode_list[] = {{
{unicode_list}
}};
""" + "".join(font_source(size) for size in SIZES)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(CODEPOINTS)} glyphs at {', '.join(map(str, SIZES))} px")


if __name__ == "__main__":
    main()
